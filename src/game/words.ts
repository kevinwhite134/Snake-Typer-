const bounds = { easy: [3, 4], medium: [5, 6], hard: [7, 9], expert: [10, 20] } as const;
export const WORDS = Object.entries(categories).flatMap(([category, list]) => {
  const [min, max] = bounds[category as keyof typeof bounds];
  return [...new Set(list.trim().split(/\s+/))].filter((word) => word.length >= min && word.length <= max);
});

const byLength = Array.from({ length: 21 }, (_, length) => WORDS.filter((word) => word.length === length));

export function chooseWord(min: number, max: number, recent: string[], random: () => number): string {
  const length = min + Math.floor(random() * (max - min + 1));
  let pool = byLength[length].filter((word) => !recent.includes(word));
  if (!pool.length) {
    pool = byLength.slice(min, max + 1).flat().filter((word) => !recent.includes(word));
  }
  return pool[Math.floor(random() * pool.length)];
}
